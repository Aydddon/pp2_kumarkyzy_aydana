a = 15
b = 20

# 1. check (==)
print("a == b:", a == b)  # False

# 2. check (!=)
print("a != b:", a != b)  # True

# 3.  (>) and(<)
print("a > b:", a > b)    # False
print("a < b:", a < b)    # True

# 4. greaterthen or equal (>=)
print("a >= 15:", a >= 15)  # True

# 5. lessthen or equal (<=)
print("b <= 10:", b <= 10)  # False

